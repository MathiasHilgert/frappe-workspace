import assert from 'node:assert/strict';
import { test } from 'node:test';
import { findAiAttribution } from './attribution.mjs';

test('a message without attribution has no findings', () => {
	assert.deepEqual(findAiAttribution('feat(session): add login\n\nCloses #1'), []);
	assert.deepEqual(findAiAttribution(undefined), []);
	assert.deepEqual(findAiAttribution(null), []);
});

test('co-author trailers of AI assistants are found, trimmed', () => {
	assert.deepEqual(
		findAiAttribution('fix(x): y\n\n  Co-Authored-By: Claude <noreply@anthropic.com>  '),
		['Co-Authored-By: Claude <noreply@anthropic.com>']
	);
	assert.equal(findAiAttribution('Co-authored-by: Copilot <c@github.com>').length, 1);
	assert.equal(findAiAttribution('Co-authored-by: Bot <noreply@openai.com>').length, 1);
});

test('a human co-author is not attribution', () => {
	assert.deepEqual(findAiAttribution('Co-authored-by: Ana <ana@example.com>'), []);
});

test('generated-with footers, session links and the robot emoji are found', () => {
	assert.equal(
		findAiAttribution('Generated with [Claude Code](https://claude.com/code)').length,
		1
	);
	assert.equal(findAiAttribution('generated by an AI tool').length, 1);
	assert.equal(findAiAttribution('https://claude.ai/code/session_1').length, 1);
	assert.equal(findAiAttribution('Claude-Session: abc').length, 1);
	assert.equal(findAiAttribution('\u{1F916} done').length, 1);
});

test('only the offending lines are returned', () => {
	assert.deepEqual(findAiAttribution('ok line\nClaude-Session: abc\nother'), [
		'Claude-Session: abc'
	]);
});
